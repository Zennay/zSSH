import net from "node:net";
import { pathToFileURL } from "node:url";

const RESERVED_SUFFIXES = [".localhost", ".local", ".internal", ".test", ".invalid", ".lan"];

function fail(message) {
  throw new Error(message);
}

function normalizeHostname(hostname) {
  return String(hostname || "").replace(/^\[|\]$/g, "").toLowerCase();
}

export function validatePublicBaseUrl(value) {
  const raw = String(value || "").trim();
  if (!raw) fail("ZSSH_PUBLIC_BASE_URL is required");

  let url;
  try {
    url = new URL(raw);
  } catch {
    fail("ZSSH_PUBLIC_BASE_URL must be a valid URL");
  }

  if (url.protocol !== "https:" || url.username || url.password || url.hash) {
    fail("ZSSH_PUBLIC_BASE_URL must be HTTPS without credentials or fragment");
  }
  if (url.pathname !== "/" || url.search) {
    fail("ZSSH_PUBLIC_BASE_URL must be an HTTPS origin without path or query");
  }
  if (url.port && url.port !== "443") {
    fail("ZSSH_PUBLIC_BASE_URL must use the standard HTTPS port");
  }

  const hostname = normalizeHostname(url.hostname);
  if (!hostname || !hostname.includes(".")) {
    fail("ZSSH_PUBLIC_BASE_URL must use a public DNS hostname");
  }
  if (net.isIP(hostname)) {
    fail("ZSSH_PUBLIC_BASE_URL must not use an IP literal");
  }
  if (hostname === "localhost" || RESERVED_SUFFIXES.some(suffix => hostname.endsWith(suffix))) {
    fail("ZSSH_PUBLIC_BASE_URL must not use a local or reserved hostname");
  }
  if (["example.com", "example.net", "example.org"].some(domain => hostname === domain || hostname.endsWith("." + domain))) {
    fail("ZSSH_PUBLIC_BASE_URL must not use a documentation-only example domain");
  }

  return new URL("https://" + hostname + "/");
}

export function validateGatewayPort(value) {
  const raw = String(value ?? "").trim();
  if (!/^\d+$/.test(raw)) fail("ZSSH_PUBLIC_GATEWAY_PORT must be an integer");
  const port = Number(raw);
  if (!Number.isSafeInteger(port) || port < 1024 || port > 65535) {
    fail("ZSSH_PUBLIC_GATEWAY_PORT must be between 1024 and 65535");
  }
  if (port === 8788) {
    fail("ZSSH_PUBLIC_GATEWAY_PORT must not reuse private zssh.service port 8788");
  }
  return port;
}

export function renderPublicCaddyConfig({ publicBaseUrl, gatewayPort = 8789 } = {}) {
  const origin = validatePublicBaseUrl(publicBaseUrl);
  const port = validateGatewayPort(gatewayPort);
  return [
    "# Generated by zSSH scripts/render-public-caddy.mjs.",
    "# Public OpenAI ingress only; keep the upstream loopback-only.",
    origin.hostname + " {",
    "    reverse_proxy 127.0.0.1:" + port,
    "}",
    "",
  ].join("\n");
}

export function main({ env = process.env, stdout = process.stdout } = {}) {
  const rendered = renderPublicCaddyConfig({
    publicBaseUrl: env.ZSSH_PUBLIC_BASE_URL,
    gatewayPort: env.ZSSH_PUBLIC_GATEWAY_PORT || "8789",
  });
  stdout.write(rendered);
}

const invokedPath = process.argv[1] ? pathToFileURL(process.argv[1]).href : "";
if (invokedPath === import.meta.url) {
  try {
    main();
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 2;
  }
}
